function codeOf(emoji: string): string {
  return [...emoji.replace(/\uFE0F/g, "")].map((c) => c.codePointAt(0)!.toString(16)).join("-");
}

export function emojiSrc(emoji: string): string | null {
  const code = codeOf(emoji);
  return AVAILABLE.has(code) ? `/fluent/${code}.webp` : null;
}
